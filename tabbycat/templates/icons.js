const toPascalCase = name => name.replace(/(^|-)([a-z0-9])/g, (_, separator, letter) => letter.toUpperCase())

// Share the selected SVG icons with the HTML renderer.
export const icons = Object.fromEntries(
  Object.entries(iconNodes).map(([name, node]) => [toPascalCase(name), node]),
)

export function getIconNode (name) {
  const resolved = Object.hasOwn(legacyNames, name) ? legacyNames[name] : name
  return Object.hasOwn(iconNodes, resolved) ? iconNodes[resolved] : null
}
